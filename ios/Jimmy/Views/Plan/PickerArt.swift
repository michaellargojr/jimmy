// The two picker pictures: a shaded athletic figure for cable height, and a shaded adjustable bench for bench angle.
// Both are drawn in code, so they stay sharp at any size and follow the colour scheme.

/// The athletic figure, head and body, scaled to fit and centered.
struct AthleteShape: Shape {
    func path(in rect: CGRect) -> Path {
        let s = min(rect.width / 400, rect.height / 1000)
        let ox = rect.midX - 200 * s, oy = rect.midY - 500 * s
        var p = Path()
        for data in [ATHLETE_HEAD, ATHLETE_BODY] {
            func pt(_ i: Int) -> CGPoint { CGPoint(x: ox + data[i] * s, y: oy + data[i + 1] * s) }
            p.move(to: pt(0))
            var i = 2
            while i + 5 < data.count {
                p.addCurve(to: pt(i + 4), control1: pt(i), control2: pt(i + 2))
                i += 6
            }
            p.closeSubpath()
        }
        return p
    }
}

/// The figure with soft light from the top left and a contact shadow at the feet.
struct AthleteFigure: View {
    @Environment(\.palette) private var p

    var body: some View {
        GeometryReader { geo in
            let s = min(geo.size.width / 400, geo.size.height / 1000)
            ZStack {
                Ellipse()
                    .fill(Color.black.opacity(p.isDark ? 0.7 : 0.22))
                    .frame(width: 220 * s, height: 20 * s)
                    .blur(radius: 8 * s)
                    .position(x: geo.size.width / 2, y: geo.size.height / 2 + 500 * s)
                AthleteShape().fill(shading(s))
            }
        }
        .aspectRatio(0.4, contentMode: .fit)
    }

    private func shading(_ s: CGFloat) -> some ShapeStyle {
        let c: [UInt32] = p.isDark ? [0xF1F2F5, 0xCDD0D6, 0x959AA3] : [0xA7ABB3, 0x7C818B, 0x555A63]
        return LinearGradient(
            stops: [.init(color: Color(hex: c[0]), location: 0), .init(color: Color(hex: c[1]), location: 0.5), .init(color: Color(hex: c[2]), location: 1)],
            startPoint: UnitPoint(x: 0.15, y: 0), endPoint: UnitPoint(x: 0.85, y: 1))
            .shadow(.inner(color: Color(hex: 0x05060A).opacity(0.6), radius: 10 * s, x: -9 * s, y: -6 * s))
            .shadow(.inner(color: .white.opacity(p.isDark ? 0.8 : 0.5), radius: 3 * s, x: 5 * s, y: 5 * s))
    }
}

/// Side view of an adjustable bench, drawn in a 620 by 460 box. The back pad turns on the hinge and the
/// support arm lands on the notch ladder. Animatable, so the pad swings between angles.
struct BenchDrawing: View, Animatable {
    @Environment(\.palette) private var p
    var angle: Double
    var animatableData: Double {
        get { angle }
        set { angle = newValue }
    }

    var body: some View {
        Canvas { ctx, size in
            let s = min(size.width / 620, size.height / 460)
            ctx.translateBy(x: (size.width - 620 * s) / 2 - 50 * s, y: (size.height - 460 * s) / 2)
            ctx.scaleBy(x: s, y: s)
            draw(ctx)
        }
        .aspectRatio(620 / 460, contentMode: .fit)
    }

    private func draw(_ ctx: GraphicsContext) {
        let frame = Color(hex: 0x4A4D56), rubber = Color(hex: 0x1F2024), metal = Color(hex: 0x70747E)
        let seat = Color(hex: 0xC9CCD3)
        func part(_ g: GraphicsContext, _ x: CGFloat, _ y: CGFloat, _ w: CGFloat, _ h: CGFloat, _ r: CGFloat,
                  _ base: Color, light: Double = 0.25, dark: Double = 0.4) {
            let rect = CGRect(x: x, y: y, width: w, height: h)
            let path = Path(roundedRect: rect, cornerRadius: r, style: .continuous)
            g.fill(path, with: .color(base))
            g.fill(path, with: .linearGradient(
                Gradient(stops: [.init(color: .white.opacity(light), location: 0),
                                 .init(color: .white.opacity(0), location: 0.45),
                                 .init(color: .black.opacity(dark), location: 1)]),
                startPoint: CGPoint(x: rect.midX, y: rect.minY), endPoint: CGPoint(x: rect.midX, y: rect.maxY)))
        }

        // Contact shadow
        var shadow = ctx
        shadow.drawLayer { l in
            l.addFilter(.blur(radius: 10))
            l.fill(Path(ellipseIn: CGRect(x: 90, y: 430, width: 540, height: 24)), with: .color(.black.opacity(p.isDark ? 0.6 : 0.2)))
        }
        // Feet seen end on, rubber pads, rear handle
        part(ctx, 96, 392, 46, 40, 9, frame); part(ctx, 100, 430, 38, 10, 4, rubber, light: 0, dark: 0)
        part(ctx, 538, 392, 46, 40, 9, frame); part(ctx, 542, 430, 38, 10, 4, rubber, light: 0, dark: 0)
        part(ctx, 578, 378, 44, 14, 7, frame)
        part(ctx, 608, 372, 22, 26, 8, rubber, light: 0.08, dark: 0)
        // Spine and notch ladder
        part(ctx, 90, 372, 500, 22, 8, frame)
        for x in stride(from: CGFloat(400), through: 580, by: 20) { part(ctx, x - 5, 363, 10, 11, 3, metal, light: 0.2, dark: 0.2) }
        // Seat post and bracket
        part(ctx, 214, 304, 22, 68, 6, frame)
        part(ctx, 176, 300, 136, 10, 4, frame)
        // Support arm: fixed length, from the pad down to the ladder
        let a = CGFloat(-angle * .pi / 180)
        let ax = 300 + 90 * cos(a) - 8 * sin(a), ay = 300 + 90 * sin(a) + 8 * cos(a)
        let length: CGFloat = 190, ladderY: CGFloat = 368
        let dy = ladderY - ay
        let fx = ax + (max(0, length * length - dy * dy)).squareRoot()
        var arm = ctx
        arm.translateBy(x: ax, y: ay)
        arm.rotate(by: .radians(Double(atan2(ladderY - ay, fx - ax))))
        part(arm, -8, -8, length + 16, 16, 8, frame)
        // Seat pad
        part(ctx, 150, 268, 150, 32, 12, seat, light: 0.5, dark: 0.4)
        // Back pad and its steel channel, turned on the hinge
        var pad = ctx
        pad.translateBy(x: 300, y: 300)
        pad.rotate(by: .degrees(-angle))
        pad.translateBy(x: -300, y: -300)
        part(pad, 312, 300, 214, 9, 4, frame)
        part(pad, 304, 268, 274, 32, 12, p.accent, light: 0.45, dark: 0.4)
        // Hinge
        part(ctx, 286, 296, 28, 22, 7, frame)
        part(ctx, 295, 302, 10, 10, 3, metal, light: 0.2, dark: 0.2)
    }
}

